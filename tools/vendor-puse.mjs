// Copies the save-parsing core of PUSE (https://github.com/Zannael/PUSE, MIT)
// into src/lib/unbound/vendor/puse so the Unbound save parser has no runtime
// dependency on it.
//
// Usage: node tools/vendor-puse.mjs <path-to-PUSE-checkout>
//
// Patches applied (and nothing else):
//   1. `import x from './y.json' with { type: 'json' }` is rewritten to
//      `import x from './y.data.js'`, and each JSON table is emitted as an ES
//      module. Vite 3 / esbuild 0.15 cannot parse import attributes, while
//      Node 22+ requires them for JSON, so plain JS modules work in both.
//   2. pc.js exports `getMonBufferAndOffset` and party.js exports
//      `decodeText`, which are internal helpers we need for raw-field reads.
//   3. PUSE's id:name text catalogs (backend/data/*.txt) are emitted as
//      names.data.js, replacing its fetch-based catalog loader.
//   4. speciesConstants.json (species id -> SPECIES_* constant), which no
//      PUSE module imports, is also emitted; $lib/unbound/forms.js uses it
//      to name alternate forms.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execSync } from 'node:child_process'

const src = process.argv[2]
if (!src) {
  console.error('Usage: node tools/vendor-puse.mjs <path-to-PUSE-checkout>')
  process.exit(1)
}

// The recorded commit must describe exactly what gets vendored
const git = (cmd) => execSync(`git ${cmd}`, { cwd: src }).toString().trim()
if (git('status --porcelain')) {
  console.error(`${src} has uncommitted changes; vendor from a clean checkout`)
  process.exit(1)
}

const CORE = path.join(src, 'frontend/src/core')
const DATA = path.join(src, 'backend/data')
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'src/lib/unbound/vendor/puse')

const ENTRY = ['sections.js', 'party.js', 'pc.js', 'gameProgress.js', 'binary.js']
const EXPORTS = {
  'pc.js': 'getMonBufferAndOffset',
  'party.js': 'decodeText'
}
const NAMES = {
  species: 'pokemon.txt',
  items: 'items.txt',
  moves: 'moves.txt',
  abilities: 'abilities.txt'
}

const IMPORT_RE = /(?:import|export)\s[^;]*?from\s+['"](\.[^'"]+)['"]/g
const JSON_IMPORT_RE = /from\s+['"]\.\/([\w-]+)\.json['"]\s*with\s*\{\s*type:\s*['"]json['"]\s*\}/g

// Walk the relative import graph from the entry modules
const jsFiles = new Set()
const jsonFiles = new Set()
const walk = (file) => {
  if (jsFiles.has(file)) return
  jsFiles.add(file)
  const code = fs.readFileSync(path.join(CORE, file), 'utf8')
  for (const [, rel] of code.matchAll(IMPORT_RE)) {
    const target = path.normalize(rel)
    if (target.endsWith('.json')) jsonFiles.add(target)
    else walk(target)
  }
}
ENTRY.forEach(walk)

// Data tables we use directly rather than through a PUSE module
const EXTRA_DATA = ['speciesConstants.json']
EXTRA_DATA.forEach((f) => jsonFiles.add(f))

fs.rmSync(OUT, { recursive: true, force: true })
fs.mkdirSync(OUT, { recursive: true })

for (const file of jsFiles) {
  let code = fs.readFileSync(path.join(CORE, file), 'utf8')
  code = code.replace(JSON_IMPORT_RE, "from './$1.data.js'")
  if (/from\s+['"][^'"]+\.json['"]/.test(code)) throw new Error(`Unpatched JSON import in ${file}`)
  if (EXPORTS[file]) code += `\nexport { ${EXPORTS[file]} };\n`
  fs.writeFileSync(path.join(OUT, file), code)
}

for (const file of jsonFiles) {
  const json = fs.readFileSync(path.join(CORE, file), 'utf8')
  JSON.parse(json) // fail loudly on bad data
  const name = file.replace(/\.json$/, '.data.js')
  fs.writeFileSync(path.join(OUT, name), `export default ${json.trim()};\n`)
}

const names = {}
for (const [key, file] of Object.entries(NAMES)) {
  names[key] = {}
  for (const line of fs.readFileSync(path.join(DATA, file), 'utf8').split(/\r?\n/)) {
    const m = line.trim().match(/^(\d+):(.+)$/)
    if (m) names[key][m[1]] = m[2].trim()
  }
}
fs.writeFileSync(
  path.join(OUT, 'names.data.js'),
  `export default ${JSON.stringify(names)};\n`
)

fs.copyFileSync(path.join(src, 'LICENSE'), path.join(OUT, 'LICENSE'))

const commit = git('rev-parse HEAD')
fs.writeFileSync(
  path.join(OUT, 'VENDOR.md'),
  `# Vendored: PUSE save-parsing core

Source: https://github.com/Zannael/PUSE (MIT, see LICENSE)
Commit: ${commit}

Generated by \`tools/vendor-puse.mjs\` - do not edit by hand; re-run the
script against a newer PUSE checkout instead. See the script header for
the exact patches applied.

Modules: ${[...jsFiles].sort().join(', ')}
Data: ${[...jsonFiles].sort().join(', ')}, names.data.js
`
)

console.log(`Vendored ${jsFiles.size} modules + ${jsonFiles.size + 1} data files from ${commit.slice(0, 7)}`)
