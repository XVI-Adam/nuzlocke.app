// Generates src/lib/unbound/species.data.js: display name, form and icon for
// every Unbound species id. Re-run after re-vendoring PUSE or changing the
// pokemon icon stylesheet; test/unbound/species.test.mjs fails if stale.
//
// Usage: node tools/build-unbound-species.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { buildSpeciesTable, iconNamesFromCss } from '../src/lib/unbound/forms.js'
import names from '../src/lib/unbound/vendor/puse/names.data.js'
import constants from '../src/lib/unbound/vendor/puse/speciesConstants.data.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const ICON_CSS = path.join(ROOT, 'src/routes/assets/[resource].css/_pokemon.css')
export const OUT = path.join(ROOT, 'src/lib/unbound/species.data.js')
// The tracker's Pokémon list (Unbound applies no alias changes on top of it)
export const APP_POKEMON = path.join(ROOT, 'src/routes/api/pokemon.json/_pokemon.json')

export const generate = () => {
  const iconNames = iconNamesFromCss(fs.readFileSync(ICON_CSS, 'utf8'))
  const appPokemon = JSON.parse(fs.readFileSync(APP_POKEMON, 'utf8')).map(({ alias, name }) => ({ alias, name }))
  const table = buildSpeciesTable({ names: names.species, constants, iconNames, appPokemon })
  return `// Generated by tools/build-unbound-species.mjs - do not edit by hand.
// { [speciesId]: { name, form, formKey, label, icon, alias } }
export default ${JSON.stringify(table)};
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = generate()
  fs.writeFileSync(OUT, out)
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${(out.length / 1024).toFixed(0)} KB)`)
}
